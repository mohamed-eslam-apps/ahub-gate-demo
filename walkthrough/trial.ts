import { Scenario, launch, ownerApi } from "./lib";
const b = await launch();
const s = new Scenario(b, "S00", "Trial");
await s.open("owner");
await s.say("Release gate list", "Gate Demo product card is visible");
await s.show(s.page.getByText("Gate Demo").first(), "This is the product we gate");
await s.shell("git", ["log", "--oneline", "-3"]);
await s.verdict(true, "Overlay works", "caption · ring · cursor · terminal");
await s.finish();
await b.close();
const p = await ownerApi("GET", "/release-products");
console.log("ownerApi products:", p.status, (p.data ?? []).map((x: any) => x.name));
